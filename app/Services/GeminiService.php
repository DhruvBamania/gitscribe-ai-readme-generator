<?php

namespace App\Services;

use Illuminate\Support\Facades\Http;
use Carbon\Carbon;

class GeminiService
{
    protected $apiKey;
    protected $apiUrl;

    public function __construct()
    {
        $this->apiKey = config('services.gemini.key');
        $this->apiUrl = config('services.gemini.url');
    }

    public function generateReadme($repoName, $description, $language, $files = [], $fileContents = [])
    {
        $fileList = implode(', ', $files);

        $generationDate = now()->format('d-m-Y');
        $generationLocation = 'India';

        $deepContextBlock = "";
        if (!empty($fileContents)) {
            $deepContextBlock = "\n\nDeep Context (Raw File Contents for Analysis):\n";
            foreach ($fileContents as $fileName => $content) {
                $deepContextBlock .= "--- {$fileName} ---\n```\n{$content}\n```\n\n";
            }
            $deepContextBlock .= "Please use the Deep Context above to extract precise dependencies, exact installation commands (like npm install or composer install), and architecture details for the README.\n";
        }

        $prompt = "Act as an Expert Developer Advocate and Technical Writer. 
        I need a professional, highly readable README.md file for a GitHub project. The Markdown should feel like a premium SaaS product or a top-tier open-source library.
        
        Project Details:
        - Project Name: {$repoName}
        - Description: {$description}
        - Main Language: {$language}
        - Key Files/Directories: {$fileList}{$deepContextBlock}
        
        Formatting & UI Requirements:
        1. Hero Section: Start with an `<h1>` header, centered text, and a concise 1-sentence catchphrase.
        2. Badges: Include top-level Shields.io badges for the Tech Stack ({$language}), License (MIT), and Build Status.
        3. Table of Contents: Create a clickable Table of Contents for easy navigation.
        4. Visuals: Include a placeholder block for a project screenshot `![Project Preview](docs/preview.png)`.
        5. Clean Structure: Use horizontal rules (`---`), blockquotes (`>`) for important notes, and bolding for emphasis.
        6. Installation: Write clear, step-by-step installation instructions with proper bash code blocks assuming standard {$language} setup steps.
        7. Folder Structure: Provide a brief Markdown tree representation based on the 'Key Files' provided above.
        8. Watermark Footer: At the very bottom of the document, add a horizontal rule followed by exactly this italicized text: '*Documentation automatically generated by GitScribe on {$generationDate} ({$generationLocation}).*'
        
        CRITICAL: Output ONLY the raw Markdown code. Do not include any conversational filler before or after the code block.";

        $response = Http::timeout(120)->post($this->apiUrl . '?key=' . $this->apiKey, [
            'contents' => [
                [
                    'parts' => [
                        ['text' => $prompt]
                    ]
                ]
            ]
        ]);

        if ($response->successful()) {
            return $response->json()['candidates'][0]['content']['parts'][0]['text'];
        }

        return "Failed to generate README. Please try again.";
    }

    public function generateReadmeFromDiff($repoName, $oldReadme, $diff)
    {
        $prompt = "Act as an Expert Developer Advocate and Technical Writer. 
        You are managing the documentation for the GitHub project: {$repoName}.
        
        Below is the ORIGINAL README.md and the DIFF of the recent code changes.
        
        Task: Rewrite the entire README file exactly as the original, but seamlessly incorporate the new changes, features, or dependencies shown in the DIFF.
        
        CRITICAL RULES:
        1. Keep the exact same structure, badges, logos, and tone as the original README.
        2. Do NOT wrap your response in ```markdown ... ``` blocks. Return ONLY the raw markdown text.
        3. You MUST output the ENTIRE document from start to finish. Do not truncate, summarize, or stop halfway.
        
        ### ORIGINAL README ###
        {$oldReadme}
        
        ### RECENT CODE CHANGES (DIFF) ###
        ```diff
        {$diff}
        ```";

        $response = \Illuminate\Support\Facades\Http::timeout(120)->post($this->apiUrl . '?key=' . $this->apiKey, [
            'contents' => [
                [
                    'parts' => [
                        ['text' => $prompt]
                    ]
                ]
            ],
            'generationConfig' => [
                'maxOutputTokens' => 8192
            ]
        ]);

        if ($response->successful()) {
            $text = $response->json()['candidates'][0]['content']['parts'][0]['text'];
            
            // Robustly strip ```markdown and ``` if the AI ignores the prompt
            $text = preg_replace('/^```(?:markdown)?\s*/i', '', $text);
            $text = preg_replace('/\s*```$/', '', $text);
            
            return $text;
        }

        $errorBody = $response->body();
        \Illuminate\Support\Facades\Log::error('Gemini API Error in generateReadmeFromDiff: ' . $errorBody);

        return "Failed to generate updated README. Please try again. \n\nAPI Error Details:\n```json\n" . $errorBody . "\n```";
    }
}